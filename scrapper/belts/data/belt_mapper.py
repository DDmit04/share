"""Маппер ремней: варианты поискового запроса по строке входного xlsx.

Модель данных (`BeltData`: профиль, длина, ширина, число ручьёв) появится
позже; пока у маппера работают `get_name_variants` и унаследованное сходство
по `link`/`full_link` без бренда, поэтому он параметризован общим `EntityData`.
Когда модель будет готова, здесь появятся `COLUMN_TITLES`, `from_row` и
сравнение маркировок (`_name_similarity`), а тип заменится на
`ProductScrapperMapper[BeltData]`.
"""

import re

from scrapper.model import EntityData
from scrapper.product_mapper import ProductScrapperMapper

#: Слово, с которого начинаются названия ремней на площадках.
BELT_TYPE_WORD = 'Ремень'

#: «Ремень» в любых падежах: «ремня», «ремни», «ремней», «ремнём». Слово
#: «ремонт» под шаблон не попадает — у него другая основа.
BELT_WORD_RE = re.compile(r'\bрем(?:ень|ён|н[яеюёи]\w*)\b', re.IGNORECASE)

#: Обозначения без цифр, которые остаются в названии: «ГРМ» — ремень
#: газораспределительного механизма, «СПА», «СПБ», «СПЗ», «СПЦ» — профили
#: узкого клина, если они записаны кириллицей (латиницей они сохраняются
#: сами). Материал и профиль («резиновый», «клиновой», «поликлиновой»)
#: считаются описаниями: без них запрос шире, а полный вариант с ними всё
#: равно пробуется первым.
BELT_KEEP_WORDS = frozenset({'грм', 'спа', 'спб', 'спз', 'спц'})


class BeltScrapperMapper(ProductScrapperMapper[EntityData]):
    """Маппер ремней: поисковые запросы вокруг слова «Ремень».

    Примеры вариантов для строки «Ремень клиновой приводной Gates Z(0) 1250»:

    * «Ремень клиновой приводной Gates Z(0) 1250» — полное название;
    * «Ремень Gates Z(0) 1250» — без русских описаний;
    * «Ремень Gates Z(0)» — укороченный вариант без длины;
    * «Ремень Z(0) 1250», «Ремень Gates Z(0) 1250», «Ремень Z(0) 1250 Gates» —
      из номера детали и бренда;
    * «Gates Z(0) 1250», «Z(0) 1250 Gates», «Z(0) 1250» — без типа товара.

    Полный список зависит от заполненных полей строки: пустые пропускаются,
    повторы схлопываются. У ремней встречаются обозначения с латиницей
    (`Z(0)`, `SPB`, `6PK1053`, `HTD 8M`), поэтому описания отбрасываются
    только по-русски, а латинские обозначения остаются.
    """

    TYPE_WORDS = (BELT_TYPE_WORD,)
    TYPE_WORD_RE = BELT_WORD_RE
    KEEP_WORDS = BELT_KEEP_WORDS
