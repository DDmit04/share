"""Маппер конвейерных лент: варианты поискового запроса по строке xlsx.

Модель данных (`TapeData`: ширина, толщина, число прокладок, тип каркаса)
появится позже; пока у маппера работают `get_name_variants` и унаследованное
сходство по `link`/`full_link` без бренда, поэтому он параметризован общим
`EntityData`. Когда модель будет готова, здесь появятся `COLUMN_TITLES`,
`from_row` и сравнение маркировок (`_name_similarity`), а тип заменится на
`ProductScrapperMapper[TapeData]`.
"""

import re

from scrapper.model import EntityData
from scrapper.product_mapper import ProductScrapperMapper

#: Слово, с которого начинаются названия лент на площадках.
TAPE_TYPE_WORD = 'Лента'

#: «Лента» в любых падежах. Прилагательное «ленточный» под шаблон не
#: попадает: после основы «лент» идёт «очный», а не падежное окончание.
TAPE_WORD_RE = re.compile(r'\bлент(?:а|ы|е|у|ой|ою|ам|ами|ах)?\b', re.IGNORECASE)

#: Обозначения без цифр, которые остаются в названии: тип каркаса и свойства
#: ленты — «ТК», «БКНЛ», «МБС», «ТМКШ». Обозначения с цифрами («ТК-200»,
#: «БКНЛ-65», «ШТ-2») сохраняются сами, потому что содержат число.
#: «ШТ» отдельным словом не сохраняется: это ещё и единица «шт» в конце
#: названия. Материал («ПВХ», «ПУ») считается описанием: без него запрос
#: шире, а полный вариант с ним всё равно пробуется первым.
TAPE_KEEP_WORDS = frozenset({'тк', 'бкнл', 'мбс', 'тмкш'})


class TapeScrapperMapper(ProductScrapperMapper[EntityData]):
    """Маппер конвейерных лент: поисковые запросы вокруг слова «Лента».

    Примеры вариантов для строки «Лента конвейерная резинотканевая ТК-200
    2-500-3-1,5-2»:

    * полное название целиком;
    * «Лента ТК-200 2-500-3-1,5-2» — без описаний «конвейерная»,
      «резинотканевая»;
    * «Лента ТК-200» — укороченный вариант без обозначения;
    * «Лента 2-500-3-1,5-2», «Лента NBR 2-500-3-1,5-2» — из номера детали
      и бренда;
    * «NBR 2-500-3-1,5-2», «2-500-3-1,5-2» — без типа товара.

    Маркировка ленты — это набор чисел через дефис (число прокладок, ширина,
    толщина), поэтому цифры в ней есть всегда, и правила отбрасывания хвоста
    из общего маппера работают без изменений. Полный список зависит от
    заполненных полей строки: пустые пропускаются, повторы схлопываются.
    """

    TYPE_WORDS = (TAPE_TYPE_WORD,)
    TYPE_WORD_RE = TAPE_WORD_RE
    KEEP_WORDS = TAPE_KEEP_WORDS
