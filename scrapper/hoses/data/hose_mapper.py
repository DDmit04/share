"""Маппер шлангов: варианты поискового запроса по строке входного xlsx.

Модель данных (`HoseData`: внутренний и наружный диаметр, давление, длина)
появится позже; пока у маппера работают `get_name_variants` и унаследованное
сходство по `link`/`full_link` без бренда, поэтому он параметризован общим
`EntityData`. Когда модель будет готова, здесь появятся `COLUMN_TITLES`,
`from_row` и сравнение маркировок (`_name_similarity`), а тип заменится на
`ProductScrapperMapper[HoseData]`.
"""

import re

from scrapper.model import EntityData
from scrapper.product_mapper import ProductScrapperMapper

#: Слова, с которых начинаются названия шлангов на площадках. «Рукав» —
#: такой же обычный синоним, особенно для РВД.
HOSE_TYPE_WORDS = ('Шланг', 'Рукав')

#: «Шланг» и «Рукав» в любых падежах. Прилагательные «шланговый» и
#: «рукавный» под шаблон не попадают: у них другие окончания.
HOSE_WORD_RE = re.compile(
    r'\bшланг(?:а|у|ом|е|и|ов|ам|ами|ах)?\b'
    r'|\bрукав(?:а|у|ом|е|ов|ам|ами|ах)?\b',
    re.IGNORECASE,
)

#: Обозначения без цифр, которые остаются в названии: «РВД» — рукав высокого
#: давления, «Ду» и «Дн» — номинальный и наружный диаметр, если они записаны
#: отдельно от числа. Материал («ПВХ», «ПУ») и конструкция («напорный»,
#: «гофрированный») считаются описаниями: без них запрос шире, а полный
#: вариант с ними всё равно пробуется первым.
HOSE_KEEP_WORDS = frozenset({'рвд', 'ду', 'дн'})


class HoseScrapperMapper(ProductScrapperMapper[EntityData]):
    """Маппер шлангов: поисковые запросы вокруг слов «Шланг» и «Рукав».

    Примеры вариантов для строки «Шланг напорный РВД 1SN-08, 20 м»:

    * «Шланг напорный РВД 1SN-08, 20 м» — полное название;
    * «Шланг РВД 1SN-08, 20» — без описания «напорный» и единицы «м»;
    * «Шланг РВД 1SN-08» — укороченный вариант без длины;
    * «Шланг 1SN-08», «Рукав 1SN-08» — из номера детали;
    * «Шланг Gates 1SN-08», «Шланг 1SN-08 Gates», «Рукав Gates 1SN-08»,
      «Gates 1SN-08», «1SN-08» — с брендом и без типа товара.

    Полный список зависит от заполненных полей строки: пустые пропускаются,
    повторы схлопываются. Латинские обозначения (`1SN-08`, `DN10`, `R2`)
    остаются всегда: описания отбрасываются только по-русски.
    """

    TYPE_WORDS = HOSE_TYPE_WORDS
    TYPE_WORD_RE = HOSE_WORD_RE
    KEEP_WORDS = HOSE_KEEP_WORDS
